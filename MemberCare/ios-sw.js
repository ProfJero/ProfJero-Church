// iOS Service Worker
const CACHE_NAME = 'my-rgci-ios-v1.0.0';

self.addEventListener('install', (event) => {
    event.waitUntil(
        caches.open(CACHE_NAME)
            .then((cache) => {
                return cache.addAll([
                    '/',
                    '/index.html',
                    '/events.html',
                    '/profile.html',
                    '/offline.html',
                    '/manifest.json'
                ]);
            })
    );
});

self.addEventListener('fetch', (event) => {
    event.respondWith(
        caches.match(event.request)
            .then((response) => {
                return response || fetch(event.request);
            })
    );
});